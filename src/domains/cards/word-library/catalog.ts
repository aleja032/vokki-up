export const WORD_LIBRARY_CATEGORIES = [
  'Trabajo',
  'Viajes',
  'Día a día',
  'Frases útiles'
] as const;

export type WordLibraryCategory = (typeof WORD_LIBRARY_CATEGORIES)[number];

/** Static entries are deliberately kept separate from the user's card library. */
export type WordLibraryEntry = {
  id: string;
  term: string;
  meaning: string;
  phonetics: string;
  example: string;
  partOfSpeech: string;
  category: WordLibraryCategory;
  tags: string[];
};

type CatalogSeed = string;

function makeCatalogEntries(
  category: WordLibraryCategory,
  categoryId: string,
  rows: readonly CatalogSeed[]
): WordLibraryEntry[] {
  return rows.map(row => {
    const [term, meaning, phonetics, example, partOfSpeech] = row.split('|');
    const slug = term
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLocaleLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');

    return {
      id: `${categoryId}-${slug}`,
      term,
      meaning,
      phonetics,
      example,
      partOfSpeech,
      category,
      tags: [categoryId]
    };
  });
}

